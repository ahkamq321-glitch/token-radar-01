// Token Radar model v2 ("radar-2"): one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can score — the 40-protocol
// watchlist is the floor, never the ceiling — by an implied launch value derived only
// from the snapshot's own figures. No protocol name is ever special-cased.
//
//   implied = tvl_usd x benchmark x growthMult x maturityMult x breadthMult
//
//   benchmark  = median(mcap_usd / tvl_usd) over the snapshot's live-token protocols
//                (mcap and TVL both positive), clamped to [0.05, 1.00]. The market's
//                own ratio is the yardstick: a pre-token protocol's TVL is worth what
//                the market already pays per dollar of TVL for protocols that trade.
//   growthMult = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age unknown: 365 days)
//   breadth    = 1 + 0.02 x min(chains, 5)                (reach across chains)
//
// Age is the time since DefiLlama first listed the protocol: the best record of how
// long it has run with no token. A protocol "records no token" is never claimed to
// "have no token": the snapshot is DefiLlama's record, not proof.
//
// Live-token protocols are kept apart: the board shows the market's own market cap
// for them, never a model value.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

